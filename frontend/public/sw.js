/**
 * 설치 가능한 앱이 되기 위한 최소 서비스 워커.
 *
 * **일부러 아무것도 캐시하지 않습니다.**
 *
 * 브라우저가 "홈 화면에 설치"를 제안하려면 fetch 핸들러를 가진 서비스 워커가 있어야 합니다.
 * 그 조건만 만족시키고, 요청은 전부 그대로 네트워크로 보냅니다.
 *
 * 캐시를 하지 않는 이유:
 *
 * 1. 이 앱은 화면 대부분이 서버 데이터(레시피·기록·정확도)에 의존합니다.
 *    화면 껍데기만 캐시해도 오프라인에서 할 수 있는 일이 없습니다.
 * 2. 캐시를 두면 **낡은 버전이 남는 위험**이 생깁니다. 코드를 고쳐 올렸는데
 *    설치된 앱에는 예전 화면이 뜨는 상황이 시연 당일에 나오면 원인을 찾기 어렵습니다.
 *
 * 오프라인 지원이 실제로 필요해지면 그때 캐시 전략을 설계해서 넣습니다.
 * 지금 넣으면 얻는 것 없이 실패 지점만 하나 늘어납니다.
 */

// 새 워커가 대기하지 않고 즉시 활성화되게 합니다. 낡은 워커가 남아 있는 시간을 줄입니다.
self.addEventListener("install", () => self.skipWaiting());
self.addEventListener("activate", (event) => event.waitUntil(self.clients.claim()));

// 설치 조건을 만족시키기 위한 핸들러. respondWith를 부르지 않으므로
// 브라우저가 평소대로 네트워크에서 가져옵니다.
self.addEventListener("fetch", () => {});
